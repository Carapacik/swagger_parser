import 'dart:convert';
import 'dart:io';
import 'dart:typed_data';

import 'package:path/path.dart' as p;
import 'package:swagger_parser/swagger_parser.dart';

const _marker = '// Generated by swagger_parser. Do not edit.';

String _content(GeneratedFile file) => '$_marker\n\n${file.content}';

Future<Set<String>> _ownedFiles(Directory output) async {
  final owned = <String>{};
  await for (final FileSystemEntity entity in output.list(
    recursive: true,
    followLinks: false,
  )) {
    final String name = p
        .split(p.relative(entity.path, from: output.path))
        .join('/');
    if (name.endsWith('.dart') && entity is File && await _hasMarker(entity)) {
      owned.add(name);
    }
  }
  return owned;
}

/// Lists differences from the files the CLI would write.
Future<List<String>> checkOutput(
  Directory output,
  List<GeneratedFile> files,
) async {
  final differences = <String, String>{};
  final lockFile = File(p.join(output.path, '.swagger_parser.lock'));
  final RandomAccessFile? lock = lockFile.existsSync()
      ? await lockFile.open()
      : null;
  try {
    await lock?.lock(FileLock.blockingShared);
    final Set<String> owned = output.existsSync()
        ? await _ownedFiles(output)
        : <String>{};
    for (final file in files) {
      final String name = file.relativePath;
      final target = File(p.join(output.path, name));
      if (!_safeParents(output, name)) {
        differences[name] = 'Conflict';
      } else if (!owned.remove(name)) {
        final FileSystemEntityType type = FileSystemEntity.typeSync(
          target.path,
          followLinks: false,
        );
        differences[name] = type == FileSystemEntityType.notFound
            ? 'Missing'
            : 'Conflict';
      } else if (!await _matches(target, file)) {
        differences[name] = 'Changed';
      }
    }
    for (final name in owned) {
      differences[name] = 'Obsolete';
    }
  } finally {
    await lock?.close();
  }
  return [
    for (final name in differences.keys.toList()..sort())
      '${differences[name]}: $name',
  ];
}

bool _safeParents(Directory root, String relativePath) {
  String path = root.path;
  for (final String part in p.posix.split(p.posix.dirname(relativePath))) {
    path = p.join(path, part);
    final FileSystemEntityType type = FileSystemEntity.typeSync(
      path,
      followLinks: false,
    );
    if (type != FileSystemEntityType.notFound &&
        type != FileSystemEntityType.directory) {
      return false;
    }
  }
  return true;
}

Future<bool> _matches(File target, GeneratedFile file) async {
  final Uint8List expected = utf8.encode(_content(file));
  final Uint8List actual = await target.readAsBytes();
  if (expected.length != actual.length) {
    return false;
  }
  for (var i = 0; i < expected.length; i++) {
    if (expected[i] != actual[i]) {
      return false;
    }
  }
  return true;
}

/// Replaces CLI-owned files and removes obsolete CLI output.
Future<void> writeOutput(Directory output, List<GeneratedFile> files) async {
  await output.create(recursive: true);
  final RandomAccessFile lock = await File(
    p.join(output.path, '.swagger_parser.lock'),
  ).open(mode: FileMode.append);
  try {
    await lock.lock(FileLock.blockingExclusive);
    final Set<String> names = {for (final file in files) file.relativePath};
    final Set<String> owned = await _ownedFiles(output);
    for (final name in names) {
      if (!_safeParents(output, name)) {
        throw FileSystemException('Invalid output directory', name);
      }
      final String target = p.join(output.path, name);
      if (!owned.contains(name) &&
          FileSystemEntity.typeSync(target, followLinks: false) !=
              FileSystemEntityType.notFound) {
        throw FileSystemException('Output path already exists', target);
      }
    }

    final Directory stage = await output.createTemp('.swagger_parser-');
    var cleanup = true;
    try {
      final backups = <String, File>{};
      for (final file in files) {
        final String name = file.relativePath;
        final target = File(p.join(stage.path, name));
        await target.parent.create(recursive: true);
        await target.writeAsString(_content(file));
      }
      for (final name in owned) {
        await Directory(p.dirname(p.join(stage.path, name)))
            .create(recursive: true);
        backups[name] = await File(p.join(output.path, name))
            .copy(p.join(stage.path, '$name.bak'));
      }
      final changed = <String>[];
      try {
        for (final name in names) {
          await Directory(p.dirname(p.join(output.path, name)))
              .create(recursive: true);
          await File(p.join(stage.path, name))
              .rename(p.join(output.path, name));
          changed.add(name);
        }
        for (final String name in owned.difference(names)) {
          await File(p.join(output.path, name)).delete();
          changed.add(name);
        }
      } on FileSystemException {
        cleanup = false;
        for (final String name in changed.reversed) {
          final dest = File(p.join(output.path, name));
          final File? previous = backups[name];
          if (previous == null) {
            await dest.delete();
          } else {
            await previous.rename(dest.path);
          }
        }
        cleanup = true;
        rethrow;
      }
    } finally {
      if (cleanup) {
        await stage.delete(recursive: true);
      }
    }
  } finally {
    await lock.close();
  }
}

Future<bool> _hasMarker(File file) async {
  final RandomAccessFile handle = await file.open();
  try {
    final String start = latin1.decode(await handle.read(_marker.length + 2));
    return start.startsWith('$_marker\n') || start.startsWith('$_marker\r\n');
  } finally {
    await handle.close();
  }
}
